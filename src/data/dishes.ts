// Local storage helper
const STORAGE_KEY = 'sultan_mahmoud_dishes_v8_full_menu';

export const getSavedDishes = (): DishItem[] => {
  try {
    const data = localStorage.getItem(STORAGE_KEY);
    if (data) {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Error loading stored dishes:', err);
  }
  return DEFAULT_DISHES;
};

export const getStoredDishes = getSavedDishes;

export const saveDishesToStorage = (dishes: DishItem[]) => {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(dishes));
  } catch (err) {
    console.error('Error saving dishes:', err);
  }
};

export const saveStoredDishes = saveDishesToStorage;

export const resetToDefaultDishes = (): DishItem[] => {
  try {
    localStorage.removeItem(STORAGE_KEY);
  } catch (err) {
    console.error('Error clearing dishes:', err);
  }
  return DEFAULT_DISHES;
};
